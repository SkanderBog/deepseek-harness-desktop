///   （issue #715）。Unix 侧用 `exec` 转发本就没有多余层，此处与之一致。
#[cfg_attr(all(not(windows), not(test)), allow(dead_code))] // 仅 Windows 的 shim 落盘与单测使用
pub fn build_pnpm_cmd_shim(paths: &ShimPaths) -> String {
    normalize_cmd_line_endings(format!(
        r#"@echo off
rem DeepSeek Harness Desktop - pnpm command shim (generated)
rem Do not edit: regenerated by the desktop app on install/startup.
setlocal
set "NODE_BIN={node_bin}"
set "NODE_DIR={node_dir}"
set "PNPM_BIN={pnpm_bin}"
rem Runtime override: this file is read through the console code page, so a baked
rem path containing non-ASCII (e.g. user name) is corrupted on parse. The desktop
rem app passes the real path in DSH_PNPM_BIN, which arrives as UTF-16 and is safe.
if exist "%DSH_PNPM_BIN%" set "PNPM_BIN=%DSH_PNPM_BIN%"
rem Use bundled MinGit only when system Git lacks its HTTPS transport helper.
rem Never export it as GIT_DIR: that variable names a repository, not a bin dir.
set "SYSTEM_GIT_WORKS="
for /f "delims=" %%g in ('git --exec-path 2^>nul') do if exist "%%g\git-remote-https.exe" set "SYSTEM_GIT_WORKS=1"
if not defined SYSTEM_GIT_WORKS if exist "{git_dir}\git.exe" set "PATH={git_dir};%PATH%"

rem App-internal installs (DSH_PREFER_BUNDLED_PNPM=1) use the bundled pnpm,
rem falling back to the user's only when the bundled one is missing.
if "%DSH_PREFER_BUNDLED_PNPM%"=="1" (
  if exist "%PNPM_BIN%" goto :after_user
)

if "%DSH_PNPM_SHIM_GUARD%"=="1" if exist "%PNPM_BIN%" goto :after_user
set "DSH_PNPM_SHIM_GUARD=1"

rem Use the exact user pnpm discovered by the desktop app.
if defined DSH_PNPM (
  if exist "%DSH_PNPM%" goto :use_selected
)

rem Prefer a user-installed pnpm (skip our own shim dir), fall back to bundled.
rem Accept only executable extensions (.cmd/.exe/.bat), ignore extensionless shell scripts.
set "SELF_PREFIX=%~dp0"
set "SELF_PREFIX=%SELF_PREFIX:~0,-1%"
set "USER_PNPM="
for /f "delims=" %%p in ('where pnpm 2^>nul') do (
  if not defined USER_PNPM (
    if /i not "%%p"=="%SELF_PREFIX%\pnpm.cmd" (
      if /i not "%%p"=="%SELF_PREFIX%\pnpm.exe" (
        if /i not "%%p"=="%SELF_PREFIX%\pnpm.bat" (
          if /i "%%~xp"==".cmd" set "USER_PNPM=%%p"
          if /i "%%~xp"==".exe" set "USER_PNPM=%%p"
          if /i "%%~xp"==".bat" set "USER_PNPM=%%p"
        )
      )
    )
  )
)
if defined USER_PNPM goto :use_user

goto :after_user

rem Forward by invoking the target directly, never through `call`. `cmd.exe` hands
rem the raw `%*` to a batch file, which re-expands it once more, so `call` adds a
rem second interpretation layer on top of the one the caller already accounted for.
rem `dsh plugin` starts pnpm through execa, which caret-escapes every argument
rem exactly once for the single batch hop it resolves (this shim); the extra layer
rem turned `dsh-better-sidebar@^0.21.1` into `^^0.21.1` (issue #715: pnpm failed
rem with ERR_PNPM_SPEC_NOT_SUPPORTED_BY_ANY_RESOLVER, so no preset plugin installed)
rem and mangled `%`/`&` in other arguments as well. Handing `%*` straight to the
rem target keeps arguments byte-identical. A batch target transfers control, so its
rem exit code is ours; a `.exe`/`.com` target returns, and `exit /b %ERRORLEVEL%`
rem still forwards its code (issue #130).
:use_selected
if exist "%PNPM_BIN%" goto :forward_selected
if defined DSH_PNPM_SHIM_CHAIN goto :append_selected
set "DSH_PNPM_SHIM_CHAIN=1"
goto :forward_selected
:append_selected
if not "%DSH_PNPM_SHIM_CHAIN:~15,1%"=="" goto :reentry_limit
set "DSH_PNPM_SHIM_CHAIN=%DSH_PNPM_SHIM_CHAIN%1"
:forward_selected
"%DSH_PNPM%" %*
exit /b %ERRORLEVEL%

:use_user
if exist "%PNPM_BIN%" goto :forward_user
if defined DSH_PNPM_SHIM_CHAIN goto :append_user
set "DSH_PNPM_SHIM_CHAIN=1"
goto :forward_user
:append_user
if not "%DSH_PNPM_SHIM_CHAIN:~15,1%"=="" goto :reentry_limit
set "DSH_PNPM_SHIM_CHAIN=%DSH_PNPM_SHIM_CHAIN%1"
:forward_user
"%USER_PNPM%" %*
exit /b %ERRORLEVEL%

:reentry_limit
1>&2 echo [pnpm] PNPM_REENTRY_LIMIT: Recursive forwarding exceeded 16 calls.
exit /b 1

:after_user
{node_resolve}
:launch
if not exist "%PNPM_BIN%" goto :no_pnpm
"%NODE%" "%PNPM_BIN%" %*
exit /b %ERRORLEVEL%

:no_pnpm
echo [pnpm] pnpm not found. Please run DeepSeek Harness Desktop to install it first. 1>&2
exit /b 1

:no_node
echo [pnpm] Node.js runtime not found. Please run DeepSeek Harness Desktop to install it first. 1>&2
exit /b 1
"#,
        node_bin = portable_path_cmd(&paths.node_bin),
        node_dir = portable_path_cmd(&paths.node_dir()),
        git_dir = portable_path_cmd(&paths.git_dir()),
        pnpm_bin = portable_path_cmd(&paths.pnpm_bin),
        node_resolve = CMD_NODE_RESOLVE,
    ))
}

#[cfg_attr(all(not(windows), not(test)), allow(dead_code))] // 仅 Windows 的 shim 落盘与单测使用
pub fn build_pnpm_ps1_shim(paths: &ShimPaths) -> String {
    format!(
        r#"# DeepSeek Harness Desktop - pnpm command shim (generated)
# Do not edit: regenerated by the desktop app on install/startup.
$ErrorActionPreference = "Stop"
$nodeBin = '{node_bin}'
$nodeDir = '{node_dir}'
$gitDir = '{git_dir}'
$pnpmBin = '{pnpm_bin}'
# Runtime override: the baked literal may be non-ASCII; the desktop app passes the
# real path in DSH_PNPM_BIN (see the cmd shim note).
if ($env:DSH_PNPM_BIN -and (Test-Path -LiteralPath $env:DSH_PNPM_BIN -PathType Leaf)) {{ $pnpmBin = $env:DSH_PNPM_BIN }}
# Use bundled MinGit only when system Git lacks its HTTPS transport helper.
$systemGitWorks = $false
try {{
    $gitExecPath = & git --exec-path 2> $null
    $systemGitWorks = ($LASTEXITCODE -eq 0) -and (Test-Path -LiteralPath (Join-Path $gitExecPath 'git-remote-https.exe'))
}} catch {{}}
if (-not $systemGitWorks -and $gitDir -and (Test-Path -LiteralPath (Join-Path $gitDir 'git.exe'))) {{
    $env:PATH = $gitDir + ';' + $env:PATH
}}

$hasBundled = Test-Path -LiteralPath $pnpmBin -PathType Leaf
$useBundled = $env:DSH_PREFER_BUNDLED_PNPM -eq '1' -and $hasBundled

if (-not $useBundled -and -not ($hasBundled -and $env:DSH_PNPM_SHIM_GUARD -eq '1')) {{
    # The guard must not outlive this call: `$env:` writes are process-wide, so a
    # forwarded pnpm would leave DSH_PNPM_SHIM_GUARD set in the caller's shell and
    # send every later pnpm call straight to the bundled one. The cmd shim is
    # immune through `setlocal`; PowerShell has no equivalent.
    $guardBefore = $env:DSH_PNPM_SHIM_GUARD
    $chainBefore = $env:DSH_PNPM_SHIM_CHAIN

    # Use the exact user pnpm discovered by the desktop app.
    if ($env:DSH_PNPM -and (Test-Path -LiteralPath $env:DSH_PNPM -PathType Leaf)) {{
        try {{
            if (-not $hasBundled) {{
                if ($chainBefore.Length -ge 16) {{
                    [Console]::Error.WriteLine('[pnpm] PNPM_REENTRY_LIMIT: Recursive forwarding exceeded 16 calls.')
                    exit 1
                }}
                $env:DSH_PNPM_SHIM_CHAIN = $chainBefore + '1'
            }}
            $env:DSH_PNPM_SHIM_GUARD = '1'
            & $env:DSH_PNPM @args
        }} finally {{
            $env:DSH_PNPM_SHIM_GUARD = $guardBefore
            $env:DSH_PNPM_SHIM_CHAIN = $chainBefore
        }}
        exit $LASTEXITCODE
    }}

    # Prefer a user-installed pnpm (skip our own shim dir), fall back to bundled.
    $selfDir = $PSScriptRoot.TrimEnd('\') + '\'
    $userPnpm = Get-Command pnpm -All -ErrorAction SilentlyContinue |
        Where-Object {{ $_.Source -and -not $_.Source.StartsWith($selfDir, [System.StringComparison]::OrdinalIgnoreCase) }} |
        Select-Object -First 1
    if ($userPnpm) {{
        try {{
            if (-not $hasBundled) {{
                if ($chainBefore.Length -ge 16) {{
                    [Console]::Error.WriteLine('[pnpm] PNPM_REENTRY_LIMIT: Recursive forwarding exceeded 16 calls.')
                    exit 1
                }}
                $env:DSH_PNPM_SHIM_CHAIN = $chainBefore + '1'
            }}
            $env:DSH_PNPM_SHIM_GUARD = '1'
            & $userPnpm.Source @args
        }} finally {{
            $env:DSH_PNPM_SHIM_GUARD = $guardBefore
            $env:DSH_PNPM_SHIM_CHAIN = $chainBefore
        }}
        exit $LASTEXITCODE
    }}
}}

{node_resolve}

if (-not (Test-Path -LiteralPath $pnpmBin)) {{
    Write-Error '[pnpm] pnpm not found. Please run DeepSeek Harness Desktop to install it first.'
    exit 1
}}
& $node $pnpmBin @args
exit $LASTEXITCODE
"#,
        node_bin = escape_path_ps1(&paths.node_bin),
        node_dir = escape_path_ps1(&paths.node_dir()),
        git_dir = escape_path_ps1(&paths.git_dir()),
        pnpm_bin = escape_path_ps1(&paths.pnpm_bin),
        node_resolve = PS1_NODE_RESOLVE,
    )
}

#[cfg_attr(all(windows, not(test)), allow(dead_code))]
pub fn build_pnpm_sh_shim(paths: &ShimPaths) -> String {
    format!(
        r#"#!/bin/sh
# DeepSeek Harness Desktop - pnpm command shim (generated)
# Do not edit: regenerated by the desktop app on install/startup.
NODE_BIN='{node_bin}'
NODE_DIR='{node_dir}'
PNPM_BIN='{pnpm_bin}'
# Runtime override: the desktop app passes the real bundled pnpm path here.
if [ -n "$DSH_PNPM_BIN" ] && [ -f "$DSH_PNPM_BIN" ]; then PNPM_BIN="$DSH_PNPM_BIN"; fi

USE_BUNDLED=
if [ "$DSH_PREFER_BUNDLED_PNPM" = "1" ] && [ -f "$PNPM_BIN" ]; then
  USE_BUNDLED=1
fi

if [ -z "$USE_BUNDLED" ] && ! {{ [ "$DSH_PNPM_SHIM_GUARD" = "1" ] && [ -f "$PNPM_BIN" ]; }}; then
  # Use the exact user pnpm discovered by the desktop app unless bundled was requested.
  if [ -n "$DSH_PNPM" ] && [ -x "$DSH_PNPM" ]; then
    if [ ! -f "$PNPM_BIN" ]; then
      if [ "${{#DSH_PNPM_SHIM_CHAIN}}" -ge 16 ]; then
        echo "[pnpm] PNPM_REENTRY_LIMIT: Recursive forwarding exceeded 16 calls." >&2
        exit 1
      fi
      DSH_PNPM_SHIM_CHAIN="${{DSH_PNPM_SHIM_CHAIN}}1"
      export DSH_PNPM_SHIM_CHAIN
    fi
    DSH_PNPM_SHIM_GUARD=1
    export DSH_PNPM_SHIM_GUARD
    exec "$DSH_PNPM" "$@"
  fi

  # Prefer a user-installed pnpm (skip our own shim dir), fall back to bundled.
  SELF_DIR=$(cd "$(dirname "$0")" && pwd)
  IFS=:
  for dir in $PATH; do
    if [ "$dir" = "$SELF_DIR" ]; then
      continue
    fi
    if [ -x "$dir/pnpm" ]; then
      if [ ! -f "$PNPM_BIN" ]; then
        if [ "${{#DSH_PNPM_SHIM_CHAIN}}" -ge 16 ]; then
          echo "[pnpm] PNPM_REENTRY_LIMIT: Recursive forwarding exceeded 16 calls." >&2
          exit 1
        fi
        DSH_PNPM_SHIM_CHAIN="${{DSH_PNPM_SHIM_CHAIN}}1"
        export DSH_PNPM_SHIM_CHAIN
      fi
      DSH_PNPM_SHIM_GUARD=1
      export DSH_PNPM_SHIM_GUARD
      exec "$dir/pnpm" "$@"
    fi
  done
  unset IFS
fi

{node_resolve}

if [ ! -f "$PNPM_BIN" ]; then
  echo "[pnpm] pnpm not found. Please run DeepSeek Harness Desktop to install it first." >&2
  exit 1
fi
exec "$NODE" "$PNPM_BIN" "$@"
"#,
        node_bin = escape_path_sh(&paths.node_bin),
        node_dir = escape_path_sh(&paths.node_dir()),
        pnpm_bin = escape_path_sh(&paths.pnpm_bin),
        node_resolve = SH_NODE_RESOLVE,
    )
}

fn build_npm_cli_cmd_shim(
    paths: &ShimPaths,
    shim_name: &str,
    cli_file: &str,
    bundled_cli: &Path,
) -> String {
    normalize_cmd_line_endings(format!(
        r#"@echo off
rem DeepSeek Harness Desktop - {shim_name} command shim (generated)
rem Do not edit: regenerated by the desktop app on install/startup.
setlocal
set "NODE_BIN={node_bin}"
set "NODE_DIR={node_dir}"
rem Use bundled MinGit only when system Git lacks its HTTPS transport helper.
rem Never export it as GIT_DIR: that variable names a repository, not a bin dir.
set "SYSTEM_GIT_WORKS="
for /f "delims=" %%g in ('git --exec-path 2^>nul') do if exist "%%g\git-remote-https.exe" set "SYSTEM_GIT_WORKS=1"
if not defined SYSTEM_GIT_WORKS if exist "{git_dir}\git.exe" set "PATH={git_dir};%PATH%"
{node_resolve}
rem CMD_NODE_RESOLVE jumps here for every node it accepts, so the cli lookup
rem below must sit at :launch rather than after a separate label.
:launch
rem The cli entry ships with npm, so it is looked up next to the node that will
rem run it: a version manager's node directory may hold no npm at all, and a
rem relative wrapper cannot reach one.
set "NPM_CLI="
set "NPM_NODE_DIR="
if /i "%NODE%"=="node" goto :npm_node_from_path
for %%c in ("%NODE%") do set "NPM_NODE_DIR=%%~dpc"
goto :npm_node_dir_ready
:npm_node_from_path
for /f "delims=" %%c in ('where node 2^>nul') do if not defined NPM_NODE_DIR set "NPM_NODE_DIR=%%~dpc"
:npm_node_dir_ready
rem Issue #1042: version-manager launchers are not the actual Node installation.
for /f "delims=" %%c in ('""%NODE%" -p "process.execPath" 2^>nul"') do if exist "%%c" set "NPM_NODE_DIR=%%~dpc"
for %%c in (
  "%NPM_NODE_DIR%node_modules\npm\bin\{cli_file}"
  "%NPM_NODE_DIR%lib\node_modules\npm\bin\{cli_file}"
  "%NPM_NODE_DIR%..\lib\node_modules\npm\bin\{cli_file}"
) do if not defined NPM_CLI if exist "%%~c" set "NPM_CLI=%%~c"
if defined NPM_CLI goto :npm_run
rem The bundled runtime always carries its own npm installation.
if exist "{bundled_cli}" set "NPM_CLI={bundled_cli}"
if defined NPM_CLI goto :npm_run

rem No usable npm next to node: forward the user's own {shim_name} instead
rem (skipping our own shim dir, and only executable extensions).
set "SELF_PREFIX=%~dp0"
set "SELF_PREFIX=%SELF_PREFIX:~0,-1%"
set "USER_NPM="
for /f "delims=" %%p in ('where {shim_name} 2^>nul') do (
  if not defined USER_NPM (
    if /i not "%%p"=="%SELF_PREFIX%\{shim_name}.cmd" (
      if /i not "%%p"=="%SELF_PREFIX%\{shim_name}.exe" (
        if /i not "%%p"=="%SELF_PREFIX%\{shim_name}.bat" (
          if /i "%%~xp"==".cmd" set "USER_NPM=%%p"
          if /i "%%~xp"==".exe" set "USER_NPM=%%p"
          if /i "%%~xp"==".bat" set "USER_NPM=%%p"
        )
      )
    )
  )
)
if not defined USER_NPM goto :no_npm
if not defined DSH_NPM_SHIM_CHAIN goto :npm_forward_user
for %%c in ("%DSH_NPM_SHIM_CHAIN:;=" "%") do if /i "%%~c"=="%USER_NPM%" goto :npm_reentry_limit
:npm_forward_user
set "DSH_NPM_SHIM_CHAIN=%DSH_NPM_SHIM_CHAIN%;%USER_NPM%"
rem Forward by invoking the target directly, never through `call`: the extra
rem interpretation layer re-expands %* and mangles already-escaped arguments.
"%USER_NPM%" %*
exit /b %ERRORLEVEL%

:npm_run
if not exist "%NPM_CLI%" goto :no_npm
"%NODE%" "%NPM_CLI%" %*
exit /b %ERRORLEVEL%

:npm_reentry_limit
1>&2 echo [{shim_name}] NPM_REENTRY_LIMIT: Recursive forwarding revisited the same command.
exit /b 1

:no_npm
echo [{shim_name}] npm cli not found. Please run DeepSeek Harness Desktop to install it first. 1>&2
exit /b 1

:no_node
echo [{shim_name}] Node.js runtime not found. Please run DeepSeek Harness Desktop to install it first. 1>&2
exit /b 1
"#,
        node_bin = portable_path_cmd(&paths.node_bin),
        node_dir = portable_path_cmd(&paths.node_dir()),
        git_dir = portable_path_cmd(&paths.git_dir()),
        bundled_cli = portable_path_cmd(bundled_cli),
        shim_name = shim_name,
        cli_file = cli_file,
        node_resolve = CMD_NODE_RESOLVE,
    ))
}

